// extractInterfaceName gets the interface name from the owner annotation.
// "req.nephio.org/v1alpha1.Interface.n3" → "n3"
func extractInterfaceName(owner string) string {
	if owner == "" {
		return ""
	}
	parts := strings.Split(owner, ".")
	if len(parts) < 2 {
		return ""
	}
	// Verify it's an Interface resource
	if parts[len(parts)-2] != "Interface" {
		return ""
	}
	return parts[len(parts)-1]
}

// findValue finds the value node for a given key in a mapping node.
func findValue(mapping *yaml.Node, key string) *yaml.Node {
	if mapping == nil || mapping.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(mapping.Content)-1; i += 2 {
		if mapping.Content[i].Value == key {
			return mapping.Content[i+1]
		}
	}
	return nil
}

// findValueNode is the same as findValue — returns the value node for a key.
func findValueNode(mapping *yaml.Node, key string) *yaml.Node {
	return findValue(mapping, key)
}

// getScalar traverses nested mappings to get a scalar value.
// e.g. getScalar(item, "kind") or getScalar(item, "metadata", "name")
func getScalar(node *yaml.Node, keys ...string) string {
	current := node
	for _, key := range keys {
		current = findValue(current, key)
		if current == nil {
			return ""
		}
	}
	if current.Kind == yaml.ScalarNode {
		return current.Value
	}
	return ""
}

// getAnnotationValue finds an annotation value in an annotations mapping node.
// Handles annotation keys that may contain dots and slashes.
func getAnnotationValue(annotations *yaml.Node, key string) string {
	if annotations == nil || annotations.Kind != yaml.MappingNode {
		return ""
	}
	for i := 0; i < len(annotations.Content)-1; i += 2 {
		if annotations.Content[i].Value == key {
			return annotations.Content[i+1].Value
		}
	}
	return ""
}


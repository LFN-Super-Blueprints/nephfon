type resultEntry struct {
	Message  string
	Severity string
}

// appendResults adds result entries to the ResourceList for pipeline logging.
func appendResults(root *yaml.Node, results []resultEntry) {
	if len(results) == 0 {
		return
	}

	// Build the results sequence node
	resultsSeq := &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq"}
	for _, r := range results {
		entry := &yaml.Node{
			Kind: yaml.MappingNode,
			Tag:  "!!map",
			Content: []*yaml.Node{
				{Kind: yaml.ScalarNode, Value: "message", Tag: "!!str"},
				{Kind: yaml.ScalarNode, Value: r.Message, Tag: "!!str"},
				{Kind: yaml.ScalarNode, Value: "severity", Tag: "!!str"},
				{Kind: yaml.ScalarNode, Value: r.Severity, Tag: "!!str"},
			},
		}
		resultsSeq.Content = append(resultsSeq.Content, entry)
	}

	// Append or replace "results" in root
	for i := 0; i < len(root.Content)-1; i += 2 {
		if root.Content[i].Value == "results" {
			root.Content[i+1] = resultsSeq
			return
		}
	}
	// Key doesn't exist — append it
	root.Content = append(root.Content,
		&yaml.Node{Kind: yaml.ScalarNode, Value: "results", Tag: "!!str"},
		resultsSeq,
	)
}

// writeOutput encodes the document to the provided writer.
func writeOutput(doc *yaml.Node, w io.Writer) error {
	enc := yaml.NewEncoder(w)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return fmt.Errorf("encoding output: %w", err)
	}
	return enc.Close()
}

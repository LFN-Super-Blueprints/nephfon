// nad-master-fn is a KRM function that controls how NetworkAttachmentDefinition
// (NAD) "master" fields are set, supporting two networking modes:
//
//   - networking-mode: "nic" (default)
//     Replaces the macvlan "master" field in each NAD's spec.config JSON
//     with a physical NIC name, bypassing Nephio's VLAN layer entirely.
//     Pods attach directly to the physical interface (e.g. ens1f0).
//
//   - networking-mode: "vlan"
//     Leaves the NADs untouched. Nephio's native flow stands:
//     Interface (attachmentType: vlan) -> VLANClaim (vlan-specializer) ->
//     nad-fn renders master: <masterInterface>.<vlanID> (e.g. ens4f0.6).
//     The vlan-agent DaemonSet (networking/vlan-agent package) creates the
//     VLAN sub-interfaces on the nodes automatically.
//
// In "nic" mode it reads interface-to-NIC mappings from the functionConfig
// (ConfigMap), identifies each NAD by its specializer.nephio.org/owner
// annotation, parses the spec.config JSON properly, replaces only the
// "master" field, and serializes clean JSON back — preserving all other
// fields (mode, ipam, tuning).
//
// Usage in Kptfile:
//
//	pipeline:
//	  mutators:
//	    - image: docker.io/rehanfazal47/nad-master-fn:v2.0
//	      configPath: interface-setters.yaml
//
// Usage in PackageVariant:
//
//	pipeline:
//	  mutators:
//	    - image: docker.io/rehanfazal47/nad-master-fn:v2.0
//	      configMap:
//	        networking-mode: nic
//	        n3-interface: ens1f0
//	        n4-interface: eno49
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	if err := Process(os.Stdin, os.Stdout); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

// Process reads a kpt ResourceList from r and writes the mutated list to w.
func Process(r io.Reader, w io.Writer) error {
	// Read the full ResourceList YAML from stdin
	input, err := io.ReadAll(r)
	if err != nil {
		return fmt.Errorf("reading stdin: %w", err)
	}

	// Parse as yaml.Node tree (preserves all structure, comments, ordering)
	var doc yaml.Node
	if err := yaml.Unmarshal(input, &doc); err != nil {
		return fmt.Errorf("parsing YAML: %w", err)
	}

	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return fmt.Errorf("expected a YAML document")
	}
	root := doc.Content[0] // root mapping of ResourceList

	// ── Step 0: Determine the networking mode ────────────────────────
	// "nic"  (default): replace NAD masters with physical NIC names
	// "vlan": leave NADs untouched — keep Nephio's native
	//         <masterInterface>.<vlanID> masters generated by nad-fn
	mode := extractNetworkingMode(root)
	switch mode {
	case "vlan":
		appendResults(root, []resultEntry{{
			Message:  "networking-mode=vlan: NAD masters left as generated by nad-fn (native Nephio VLAN flow); ensure the vlan-agent is deployed on the workload cluster",
			Severity: "info",
		}})
		return writeOutput(&doc, w)
	case "", "nic":
		// fall through to NIC replacement below
	default:
		return fmt.Errorf("invalid networking-mode %q: must be \"nic\" or \"vlan\"", mode)
	}

	// ── Step 1: Extract NIC mappings from functionConfig.data ────────
	nicMap := extractNICMappings(root)
	if len(nicMap) == 0 {
		// No mappings provided — pass everything through unchanged
		return writeOutput(&doc, w)
	}

	// ── Step 2: Process items — find NADs and replace master ─────────
	var results []resultEntry
	itemsNode := findValue(root, "items")
	if itemsNode != nil && itemsNode.Kind == yaml.SequenceNode {
		for _, item := range itemsNode.Content {
			if item.Kind == yaml.MappingNode {
				if msg := processNAD(item, nicMap); msg != "" {
					results = append(results, resultEntry{
						Message:  msg,
						Severity: "info",
					})
				}
			}
		}
	}

	// ── Step 3: Append results to ResourceList ───────────────────────
	appendResults(root, results)

	// ── Step 4: Write modified ResourceList to stdout ────────────────
	return writeOutput(&doc, w)
}


// extractNetworkingMode reads functionConfig.data["networking-mode"].
// Returns "" when the key is absent (treated as "nic" for backward
// compatibility with v1.0 configs).
func extractNetworkingMode(root *yaml.Node) string {
	fc := findValue(root, "functionConfig")
	if fc == nil {
		return ""
	}
	data := findValue(fc, "data")
	if data == nil || data.Kind != yaml.MappingNode {
		return ""
	}
	for i := 0; i < len(data.Content)-1; i += 2 {
		if data.Content[i].Value == "networking-mode" {
			return strings.TrimSpace(data.Content[i+1].Value)
		}
	}
	return ""
}

// extractNICMappings reads functionConfig.data and returns a map of
// interface keys to NIC names.
// e.g. {"n3-interface": "ens1f0", "n4-interface": "eno49"}
func extractNICMappings(root *yaml.Node) map[string]string {
	nicMap := make(map[string]string)

	fc := findValue(root, "functionConfig")
	if fc == nil {
		return nicMap
	}

	data := findValue(fc, "data")
	if data == nil || data.Kind != yaml.MappingNode {
		return nicMap
	}

	for i := 0; i < len(data.Content)-1; i += 2 {
		key := data.Content[i].Value
		val := strings.TrimSpace(data.Content[i+1].Value)
		if strings.HasSuffix(key, "-interface") && val != "" {
			nicMap[key] = val
		}
	}
	return nicMap
}


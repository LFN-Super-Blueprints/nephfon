// processNAD checks if an item is a NAD and replaces the macvlan master field.
// Returns a message string if a replacement was made, empty string otherwise.
func processNAD(item *yaml.Node, nicMap map[string]string) string {
	// Only process NetworkAttachmentDefinition resources
	kind := getScalar(item, "kind")
	if kind != "NetworkAttachmentDefinition" {
		return ""
	}

	// Get the interface name from the owner annotation
	// e.g. "req.nephio.org/v1alpha1.Interface.n3" → "n3"
	metadata := findValue(item, "metadata")
	if metadata == nil {
		return ""
	}
	annotations := findValue(metadata, "annotations")
	if annotations == nil {
		return ""
	}
	owner := getAnnotationValue(annotations, "specializer.nephio.org/owner")
	ifName := extractInterfaceName(owner)
	if ifName == "" {
		return ""
	}

	// Look up the desired NIC for this interface
	nicKey := ifName + "-interface" // e.g. "n3-interface"
	desiredNIC, exists := nicMap[nicKey]
	if !exists {
		return "" // no mapping for this interface — leave unchanged
	}

	// Get spec.config (the JSON string inside the NAD)
	spec := findValue(item, "spec")
	if spec == nil {
		return ""
	}
	configNode := findValueNode(spec, "config")
	if configNode == nil || configNode.Kind != yaml.ScalarNode {
		return ""
	}

	configStr := configNode.Value

	// Parse the NAD config as JSON
	var config map[string]interface{}
	if err := json.Unmarshal([]byte(configStr), &config); err != nil {
		return fmt.Sprintf("warning: could not parse NAD config JSON: %v", err)
	}

	// Find the macvlan plugin and replace its "master" field
	plugins, ok := config["plugins"].([]interface{})
	if !ok {
		return ""
	}

	modified := false
	for i, p := range plugins {
		pluginMap, ok := p.(map[string]interface{})
		if !ok {
			continue
		}
		if pluginMap["type"] == "macvlan" {
			pluginMap["master"] = desiredNIC
			plugins[i] = pluginMap
			modified = true
		}
	}

	if !modified {
		return ""
	}

	config["plugins"] = plugins

	// Serialize the modified JSON back
	newJSON, err := json.Marshal(config)
	if err != nil {
		return fmt.Sprintf("warning: could not marshal NAD config: %v", err)
	}

	// Write the new JSON string back to spec.config
	configNode.Value = string(newJSON)
	configNode.Tag = "!!str"
	configNode.Style = 0 // let the encoder decide formatting

	nadName := getScalar(metadata, "name")
	return fmt.Sprintf("set master=%q for NAD %s (interface %s)", desiredNIC, nadName, ifName)
}

